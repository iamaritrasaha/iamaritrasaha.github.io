// Reproduce the no-JavaScript image with the same depth-tested renderer.
// Start npm start first. Optional: PORT=4173 PLAYWRIGHT_CHANNEL=chromium.
import { chromium } from "@playwright/test";
import { writeFile } from "node:fs/promises";
const browser = await chromium.launch({
  channel: process.env.PLAYWRIGHT_CHANNEL || "chromium",
});
try {
  const page = await browser.newPage();
  await page.goto(
    `http://127.0.0.1:${process.env.PORT || 4173}/?motion=reduce`,
  );
  const png = await page.evaluate(async () => {
    const { createSculpture } = await import(
      "/assets/projection-renderer.js?v=s1"
    );
    const { VIEW } = await import("/assets/projection.js?v=s1");
    const canvas = document.createElement("canvas");
    canvas.width = 1200;
    canvas.height = 900;
    createSculpture(canvas)(VIEW.initial);
    return canvas.toDataURL("image/png");
  });
  await writeFile(
    "assets/helicoid.svg",
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="800" height="600"><title>Helicoid at 22 degrees</title><desc>Depth-tested shaded surface, generated by scripts/render_projection.mjs. Geometry and camera match the interactive Canvas study.</desc><image width="800" height="600" href="${png}"/></svg>\n`,
  );
} finally {
  await browser.close();
}
